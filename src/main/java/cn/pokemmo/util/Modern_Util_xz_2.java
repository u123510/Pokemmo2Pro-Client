package cn.pokemmo.util;

import f.*;

/**
 * 现代化重构类 - 原始混淆类: f.xz_2
 */
public class Modern_Util_xz_2 {

    public final int m50;
    public final int CD;
    public final int A20;
    public final int Wr;
    public final int ls;
    public final int yq;
    public final int q1;
    public final boolean nUL;

    public Modern_Util_xz_2(int n, int n2, int n3, int n4, int n5, int n6, int n7, boolean bl) {
        this.m50 = n;
        this.CD = n2;
        this.A20 = n3;
        this.Wr = n4;
        this.ls = n5;
        this.yq = n6;
        this.q1 = n7;
        this.nUL = bl;
    }

    public final String toString() {
        return "r: " + this.m50 + ", g: " + this.CD + ", b: " + this.A20 + ", a: " + this.Wr + ", depth: " + this.ls + ", stencil: " + this.yq + ", num samples: " + this.q1 + ", coverage sampling: " + this.nUL;
    }
}


