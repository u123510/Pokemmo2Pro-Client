package cn.pokemmo.util;

import f.*;

/**
 * 现代化重构类 - 原始混淆类: f.P50
 */
public class Modern_Util_P50
extends SZ {

    public final byte h4;
    public final short ct;
    public final byte pS;

    public Modern_Util_P50(byte by, byte by2, short s) {
        this.h4 = by;
        this.ct = s;
        this.pS = by2;
    }

    @Override
    public final byte pA0() {
        return 1;
    }

    @Override
    public final byte Bi() {
        return 2;
    }
}


