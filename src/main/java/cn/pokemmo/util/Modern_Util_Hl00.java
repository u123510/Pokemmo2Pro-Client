package cn.pokemmo.util;

import f.*;

/**
 * 现代化重构类 - 原始混淆类: f.hl0_0
 */
public class Modern_Util_Hl00 {

    public final CH0 Br;
    public final short wQ;
    public short PA0;
    public final A5 P;
    public byte N50;
    public final byte Ps;
    public tu_2 pe;

    public Modern_Util_Hl00(CH0 cH0, short s, short s2, A5 a5, byte by, byte by2) {
        this.Br = cH0;
        this.wQ = s;
        this.PA0 = s2;
        this.P = a5;
        this.N50 = by;
        this.Ps = by2;
    }

    public final short COM8() {
        return this.wQ;
    }

    public final short Tu() {
        return this.PA0;
    }

    public final byte uI() {
        return this.N50;
    }
}


