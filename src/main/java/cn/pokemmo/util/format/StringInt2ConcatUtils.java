package cn.pokemmo.util.format;

public abstract class StringInt2ConcatUtils {
    public static String concat(String string, int n, String string2, int n2) {
        return string + n + string2 + n2;
    }

    public static String YH0(String string, int n, String string2, int n2) {
        return concat(string, n, string2, n2);
    }
}
