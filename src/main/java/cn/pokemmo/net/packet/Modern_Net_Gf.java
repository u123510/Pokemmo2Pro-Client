package cn.pokemmo.net.packet;

import f.*;
import java.nio.ByteBuffer;
import java.util.Collection;

/**
 * 现代化网络本地接口门面 - 原始混淆类: f.Gf
 * 底层 JNI 原生方法必须在 {@link Gf} 中声明以匹配动态链接库符号名
 */
public abstract class Modern_Net_Gf {

    public Modern_Net_Gf() {
        super();
    }

    public static int TJ() { return Gf.TJ(); }
    public static boolean Vb() { return Gf.Vb(); }
    public static boolean dH() { return Gf.dH(); }
    public static long jb(int i) { return Gf.jb(i); }
    public static String SH() { return Gf.SH(); }
    public static boolean mb() { return Gf.mb(); }
    public static boolean pH() { return Gf.pH(); }
    public static String Mb() { return Gf.Mb(); }
    public static String PH() { return Gf.PH(); }
    public static boolean RH() { return Gf.RH(); }
    public static long Ib() { return Gf.Ib(); }
    public static int fH() { return Gf.fH(); }
    public static long Lb() { return Gf.Lb(); }
    public static int Ub(Class clazz, Collection collection) { return Gf.Ub(clazz, collection); }
    public static int cH(Class clazz, Collection collection) { return Gf.cH(clazz, collection); }
    public static ByteBuffer kc(ByteBuffer buffer, int i, String str, long j) { return Gf.kc(buffer, i, str, j); }
}

